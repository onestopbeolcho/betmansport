function stripAccents(str: string): string {
  return str
    .replace(/ø/g, "o")
    .replace(/Ø/g, "O")
    .replace(/&/g, "and")
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "");
}

const NORM_EN_TO_KO: Record<string, string> = {};
for (const [en, ko] of Object.entries(TEAM_DISPLAY_EN_TO_KO)) {
  const norm = stripAccents(en)
    .toLowerCase()
    .replace(/\b(fc|sc|cf|afc|ssc|acf|us|ss|vfl|vfb|spvgg|rcd|ud|cd|ca|ac|as|rc|aj|ogc|nec|pec|nac|fk|sk|nk)\b/g, "")
    .replace(/[^a-z0-9]/g, "");
  if (norm) NORM_EN_TO_KO[norm] = ko;
}

export function mapTeamName(engName?: string, koName?: string): string {
  const cleanKo = (koName || "").trim();
  const cleanEn = (engName || "").trim();
  if (cleanKo && BETMAN_ABBR_TO_FULL_KO[cleanKo]) return BETMAN_ABBR_TO_FULL_KO[cleanKo];
  if (cleanEn && TEAM_DISPLAY_EN_TO_KO[cleanEn]) return TEAM_DISPLAY_EN_TO_KO[cleanEn];
  if (cleanEn) {
    const norm = stripAccents(cleanEn)
      .toLowerCase()
      .replace(/\b(fc|sc|cf|afc|ssc|acf|us|ss|vfl|vfb|spvgg|rcd|ud|cd|ca|ac|as|rc|aj|ogc|nec|pec|nac|fk|sk|nk)\b/g, "")
      .replace(/[^a-z0-9]/g, "");
    if (norm && NORM_EN_TO_KO[norm]) return NORM_EN_TO_KO[norm];
  }
  if (cleanKo && cleanKo !== cleanEn) return cleanKo;
  return cleanEn || cleanKo;
}

export function formatTeamDisplay(engName?: string, koName?: string): string {
  const cleanEn = (engName || "").trim();
  const resolvedKo = mapTeamName(cleanEn, koName);
  if (resolvedKo && cleanEn && resolvedKo !== cleanEn) {
    return `${resolvedKo} (${cleanEn})`;
  }
  return resolvedKo || cleanEn;
}
